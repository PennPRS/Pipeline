  make_option("--homedir", action = "store", default = NA, type = "character",
              help="Path to save the output folder [Required]"),
  make_option("--PennPRS_path", action = "store", default = NA, type = "character",
              help="Path to the PennPRS folder [Required]"),
  make_option("--PRSdir", action = "store", default = NA, type = "character",
              help="Path to the folder the PRS model files are saved in. Do not change file names, keep the original file names generated by PennPRS as they are [Required]"),
  make_option("--phenofile", action = "store", default = NA, type = "character",
              help="Path to the individual-level phenotype data file for PRS model evaluation. The file can be in either .txt, .tsv, .csv, or .xlsx format, with required columns for individual ID and phenotype value, and optional columns for covariate information [Required]"),
  make_option("--bfile", action = "store", default = NA, type = "character",
              help="Path to the individual-level genotype data in PLINK format ([prefix].{bim,bed,fam}). Only prefix is needed [Required]"),
  make_option("--ID_col_num", action = "store", default = NA, type = "character",
              help="Column number for individual ID [Required]"),
  make_option("--pheno_col_num", action = "store", default = NA, type = "character",
              help="Column number for phenotype value [Required]"),
  make_option("--covar_col_nums", action = "store", default = NA, type = "character",
              help="Column numbers for covariates. If multiple covariates exist, please either separate the numbers by comma (e.g., 2,3,4) or provide the range of the consecutive columns (e.g., 2-4) [Optional]"),
  # make_option("--trait", action = "store", default = NA, type = "character",
  #             help="trait name [Optional]"),
  make_option("--verbose", action="store", default=1, type="integer",
              help="Print logfile? 0 = no; 1 = yes [default: %default]")
)
opt = parse_args(OptionParser(option_list=option_list))
print(opt)


# Input: ---------
PennPRS_path = opt$PennPRS_path
PRSdir = opt$PRSdir
homedir = opt$homedir
bfile = opt$bfile
phenofile = opt$phenofile
if (is.na(opt$covar_col_nums)) covar_col_nums = NA
if (!is.na(opt$covar_col_nums)){
  if (str_detect(opt$covar_col_nums, ',')){
    covar_col_nums = as.numeric(str_split(opt$covar_col_nums,",")[[1]])
  } 
  if (str_detect(opt$covar_col_nums, '-')){
    col.ranges = as.numeric(str_split(opt$covar_col_nums,"-")[[1]])
    covar_col_nums = col.ranges[1]:col.ranges[2]
  }
  if (sum(opt$covar_col_nums == 'NA')>0) covar_col_nums = NA
}
ID_col_num = as.numeric(str_split(opt$ID_col_num,"-")[[1]])
pheno_col_num = as.numeric(str_split(opt$pheno_col_num,"-")[[1]])

plink_path = paste0(PennPRS_path, '/software/plink2')

# Evaluate performance of all PRS models in workdir


source(paste0(PennPRS_path, '/code/gwas_qc_report_generator.R'))
find_trait_file <- function(directory, trait_name, full.names = TRUE) {
  files <- list.files(directory, full.names = full.names)
  matches <- files[grepl(trait_name, basename(files), fixed = TRUE)]
  return(matches)
}


# PRS model extraction:
allfiles = list.files(PRSdir)
prsfiles = allfiles[(!str_detect(allfiles, c('README'))) & (!str_detect(allfiles, c('model_training_info')))]
prsfiles = prsfiles[(str_detect(prsfiles, c('PRS'))) & (str_detect(prsfiles, c('.txt')))]

PRS_models = sapply(1:length(prsfiles), function(x) {substr(prsfiles[x], 1, nchar(prsfiles[x]) - 4)})

results = expand.grid(PRS_Model = PRS_models)
rownames(results) = results$PRS_Model


if (!dir.exists(homedir)){
  cat(paste0("[Terminated] Job is terminated because output directory ({homedir}) does not exist\n"))
  q()
}
if (dir.exists(homedir)){
  if (is.na(homedir)){
    cat(paste0("[Terminated] Job is terminated because output directory ({homedir}) is not specified.\n"))
    q()
  }
  if (!is.na(homedir)){
    setwd(homedir)
    if ( opt$verbose >= 1 ) {
      cat(paste0("\n**************************************************************************"))
      cat(paste0("\n**************** Computing PRS for validation individuals ****************"))
      cat(paste0("\n**************************************************************************\n"))
    }
    suppressWarnings(dir.create(paste0(homedir, '/effect/')))
    suppressWarnings(dir.create(paste0(homedir, '/score/')))

    for (PRS_model in PRS_models){
      prsf = paste0(PRSdir, '/', PRS_model, '.txt')
      sc = bigreadr::fread2(prsf)[,c(2,4,6)] # only contains non-zero-effect SNPs
      write_delim(sc, file = paste0(homedir, '/effect/', PRS_model, '.txt'), delim='\t')
      
      system(paste(paste0(plink_path),
                   paste0('--score ',  homedir, '/effect/',PRS_model, '.txt'),
                   'cols=+scoresums,-scoreavgs',
                   paste0('--score-col-nums 3'),
                   paste0(' --bfile ', bfile),
                   " --threads 1",
                   paste0(' --out ', homedir, '/score/', PRS_model)))
      # print(paste('Complete computing PRS for ', PRS_model))
    }
    
    if ( opt$verbose >= 1 ) {
      cat(paste0("\n**************************************************************************"))
      cat(paste0("\n***************** Loading phenotype data for validation ******************"))
      cat(paste0("\n**************************************************************************\n"))
    }
    # if (str_detect(phenofile, '.txt')) valdat = bigreadr::fread2(paste0(phenofile))
    # if (str_detect(phenofile, '.csv')) valdat = read.csv(paste0(phenofile))
    # if (str_detect(phenofile, '.xlsx')) valdat = read_excel(paste0(phenofile))
    
    # phenofile.name = find_trait_file(phenofile, full.names = TRUE)
    valdat <- read_input_file(phenofile)
    
    valdat = valdat[, c(ID_col_num, pheno_col_num, covar_col_nums)]
    colnames(valdat) = c('id', 'y', paste0('c', 1:length(covar_col_nums)))
    valdat = valdat[complete.cases(valdat$y),]
    valdat$id = as.character(valdat$id)
    vald = valdat; rm(valdat)

    for (PRS_model in PRS_models){
      prsfile = paste0(homedir, '/score/', PRS_model, '.sscore')
      if (file.exists(prsfile)){
        preds = bigreadr::fread2(prsfile)[,c(1,5)]
        colnames(preds) = c('id','prs');
        valdat = merge(vald, preds, by='id'); rownames(valdat) = as.character(valdat$id)
        n.y.unique = length(unique(valdat$y))
        if (n.y.unique < 2){
          cat(paste0('\n *** [Terminated] Less than two distinct phenotype values were identified among the validation individuals.\n Please fix phenotype data file and retry. ***'))
          q()
        }
        if (n.y.unique == 2) {
          if (sum(!is.na(covar_col_nums)) == 0){
            if (PRS_model == PRS_models[1]) cat(paste0('\n *** Two distinct phenotype values were identified. Phenotype treated as binary. Computing AUC values. ***\n'))
            fit <- glm(formula(paste0(paste('y', paste('prs'), sep='~'))), data = valdat, family = binomial())
            score <- predict(fit, type = "response") 
            roc_obj <- roc(response = valdat$y, predictor = score, quiet = TRUE)
            results[PRS_model, 'AUC'] <- signif(auc(roc_obj), 3)
          }
          if (sum(!is.na(covar_col_nums)) > 0){
            if (PRS_model == PRS_models[1]) cat(paste0('\n *** Two distinct phenotype values were identified. Phenotype treated as binary. Computing Incremental AUC values. ***\n'))
            fit0 <- glm(formula(paste0(paste('y', paste(paste0('c',1:length(covar_col_nums)),collapse="+"), sep='~'))), data = valdat, family = binomial())
            fit1 <- glm(formula(paste0(paste('y', paste(c('prs', paste0('c',1:length(covar_col_nums))), collapse="+"), sep='~'))), data = valdat, family = binomial())
            score0 <- predict(fit0, type = "response"); score1 <- predict(fit1, type = "response")
            roc_obj0 <- roc(response = valdat$y, predictor = score0, quiet = TRUE)
            roc_obj1 <- roc(response = valdat$y, predictor = score1, quiet = TRUE)
            results[PRS_model, 'AUC (Full Model)'] <- signif(auc(roc_obj1), 3)
            results[PRS_model, 'Incremental AUC'] <- signif(auc(roc_obj1) - auc(roc_obj0), 3)
          }
        }
        if (n.y.unique > 2){
          if (sum(!is.na(covar_col_nums)) == 0){
            if (PRS_model == PRS_models[1]) cat(paste0('\n *** More than two distinct phenotype values were identified. Phenotype treated as continuous. Computing prediction R2 values. ***\n'))
            results[PRS_model, 'R2'] <- signif(cor(valdat$y, valdat$prs)^2, 3)
          }
          if (sum(!is.na(covar_col_nums)) > 0){
            if (PRS_model == PRS_models[1]) cat(paste0('\n *** More than two distinct phenotype values were identified. Phenotype treated as continuous. Computing adjusted R2 values. ***\n'))
            fit0 <- lm(formula(paste0(paste('y', paste(c(paste0('c',1:length(covar_col_nums))), collapse="+"), sep='~'))), data = valdat)
            fit1 <- lm(formula(paste0(paste('y', paste(c('prs', paste0('c',1:length(covar_col_nums))), collapse="+"), sep='~'))), data = valdat)
            score <- predict(fit1, type = "response") 
            valdat$res = fit0$residuals
            fit <- lm(res ~ prs, data = valdat)
            results[PRS_model, 'R2 (Full Model)'] <- signif(cor(score, valdat$y)^2, 3)
            results[PRS_model, 'Adjusted R2'] <- signif(summary(fit)$r.squared, 3)
          }
        }
      }
    }
    if ( opt$verbose >= 1 ) {
      cat(paste0("\n**************************************************************************"))
      cat(paste0("\n***************** Saving evalulation details and results *****************"))
      cat(paste0("\n**************************************************************************\n"))
    }
    filen<-paste0(homedir, 'README.txt')
    file.create(filen)
    zz <- file(filen, "w")
    
    print.title = paste0("PRS Evaluation completed:") # ,trait, " for ", anc
    cat(paste0("\n",paste(rep('*', nchar(print.title)+10),collapse='')), file = zz)
    cat(paste0("\n**** ", print.title, " ****"), file = zz)
    cat(paste0("\n",paste(rep('*', nchar(print.title)+10),collapse=''),'\n'), file = zz)
    if (n.y.unique == 2) {
      if (sum(is.na(covar_col_nums)) == 0){
        cat(paste0("\n Binary phenotype detected, no covariate information provided. AUC(PRS) was reported."), file = zz)
        # colnames(results)[which(colnames(results) == 'R2')] = 'AUC'
      }
      if (sum(is.na(covar_col_nums)) > 0){
        cat(paste0("\n Binary phenotype detected, ", length(covar_col_nums), " covariates adjusted. Incremental AUC of PRS was reported."), file = zz)
        cat(paste0("\n AUC (Full Model) = AUC(PRS+covariates)"), file = zz)
        cat(paste0("\n Incremental AUC = AUC(PRS+covariates) - AUC(PRS)"), file = zz)
        # colnames(results)[which(colnames(results) == 'R2')] = 'Incremental AUC'
      }
    }
    if (n.y.unique > 2) {
      if (sum(is.na(covar_col_nums)) == 0){
        cat(paste0("\n More than two distinct phenotype values detected, phenotype treated as continuous, no covariate information provided. Prediction R2 of PRS was reported."), file = zz)
        # colnames(results)[which(colnames(results) == 'R2')] = 'R2'
      }
      if (sum(is.na(covar_col_nums)) > 0){
        cat(paste0("\n More than two distinct phenotype values detected, phenotype treated as continuous, ", length(covar_col_nums), " covariates adjusted. Adjusted prediction R2 of PRS was reported."), file = zz)
        cat(paste0("\n R2 (Full Model): R2(PRS+covariates)"), file = zz)
        cat(paste0("\n Adjusted R2 calculation: regress phenotype on covariates, then regress the residual on PRS to obtain adjusted R2."), file = zz)
        # colnames(results)[which(colnames(results) == 'R2')] = 'Adjusted R2'
      }
    }
    write_delim(results, file = paste0(homedir, '/evaluation_results.txt'), delim = '\t')
    cat(paste0('\n\n* Evaluation results saved to evaluation_results.txt\n'), file = zz)
    close(zz)
    
    if ( opt$verbose >= 1 ) {
      cat(paste0("\n Job Completed!"))
    }
    
    # Clean up intermediate files:
    system(paste0('rm -rf ', paste0(homedir, '/effect/')))
    system(paste0('rm -rf ', paste0(homedir, '/score/')))

  }
}


